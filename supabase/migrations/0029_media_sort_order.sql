-- 0029_media_sort_order.sql — **사진 순서를 사용자가 정하고, 모든 기기가 같게 본다** (2026-08-06 · [user-decided])
--
-- ── 왜 ────────────────────────────────────────────────────────────────────────
-- 🔴 지금까지 사진에는 **순서가 없었다.** 목록 조회가 이랬다:
--
--     db().localMedia.where('tripId').equals(tripId).toArray()   -- 정렬 없음
--
-- id가 `uuid()`(무작위)이므로 화면에 보이는 순서는 사실상 임의였고, **기기마다 달라질 수도**
-- 있었다 — 같은 순간을 폰과 태블릿에서 열면 사진이 다른 자리에 놓인다.
--
-- 사용자 지시(2026-08-06): *"손가락으로 꾹 눌러서 순서를 변경할 수 있도록 해주고"*.
-- 그 요청에 답하려면 드래그보다 **순서 그 자체**가 먼저 필요했다.
--
-- 2026-07-27의 결정과 같은 줄기다 — *"핵심은 모든 기기에서 모든 정보를 확인해야 합니다.
-- 서버에 올라가는 순간 클라우드가 정본이 되야 합니다."* 순서는 **사용자가 만든 기록**이므로
-- 이 기기에만 두면 다른 기기에서 잃는다(0019 오디오·0024 사진 GPS와 같은 형태의 빚).
--
-- ── 무엇 ──────────────────────────────────────────────────────────────────────
--   · `media.sort_order` — integer, NULL 허용
--
-- 🔴 **NULL은 0이 아니다.** NULL = *"아직 아무도 자리를 정하지 않았다"* → 앱이 촬영시각 순으로
-- 놓는다. 0 = *"사용자가 정한 첫 번째"*. 이 앱은 `0`을 falsy로 뭉개 사용자의 기억을 기니만
-- 앞바다에 저장한 적이 있다(M-0057) — 같은 실수를 여기서 되풀이하지 않는다.
--
-- 음수는 계산 결과가 아니라 **결함**이다(앱은 언제나 0부터 다시 매긴다) → 제약으로 잠근다.
-- 상한은 두지 않는다: 한 순간의 사진 수는 사용자가 정하는 것이고, 앱이 임의로 자를 자리가 아니다.
--
-- ── 사생활·용량 ───────────────────────────────────────────────────────────────
-- 정수 하나다. 사진 바이트·EXIF와 무관하고, RLS는 기존 소유자 정책을 그대로 탄다.
--
-- 되돌리기: 컬럼을 drop 하면 된다. 옛 앱은 이 컬럼을 안 읽고 안 쓴다(무해) —
-- 순서 없이 촬영시각으로 놓던 예전 화면으로 돌아갈 뿐이다.

alter table journey.media add column if not exists sort_order integer;

alter table journey.media drop constraint if exists media_sort_order_nonneg;
alter table journey.media add constraint media_sort_order_nonneg check (
  sort_order is null or sort_order >= 0
);
