-- 0020_audio_purged_guard.sql · 소리 표에 **좀비 재삽입 차단**을 건다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 왜 0019에서 빠졌나 (§7 — 새로 만든 것은 형제의 규율을 물려받지 않는다)
-- ─────────────────────────────────────────────────────────────────────────────
-- 0019는 형제(`journey.media`)의 계약을 한 줄씩 옮겨 적었다: 소유자 RLS + 초대제 ·
-- 복합 FK(H-02) · tombstone 전용 · `set_updated_at` · **`prevent_zombie_resurrection`** ·
-- GRANT 4종. 그런데 그 목록은 **0019가 만드는 표 안에 있는 것**만 훑었다.
--
-- `block_purged_reinsert`는 다른 마이그레이션(0012)에 살면서 **네 표에 각각 트리거를 건다.**
-- 즉 형제의 규율이 형제의 파일 밖에 있었고, 그래서 새 표가 그 목록에 자동으로 들어가지 않았다.
-- **M-0033과 같은 근본형이다** — 새것은 자기가 푸는 문제로 태어나지, 형제들의 계약을 알고
-- 태어나지 않는다. 그리고 이번에도 그 규율은 문서에 **버젓이 적혀 있었다**(ADR-0030).
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 없으면 무슨 일이 벌어지나 (조용하고, 되돌릴 수 없다)
-- ─────────────────────────────────────────────────────────────────────────────
-- 영구삭제(휴지통 비우기)는 서버 행을 **실제로 지운다**(ADR-0030). 좀비를 막는 것은
-- 「행을 남기는 것」이 아니라 **「서버가 재삽입을 거부하는 것」**이고, 그 거부가 이 트리거다.
--
-- 이게 없으면: 사용자가 소리를 영구삭제 → 그 사실을 아직 모르는 다른 기기가 다음 동기화에서
-- 자기 사본을 upsert → **서버에 되살아난다.** 그리고 그 행은 원장에 id가 있으므로 이 기기의
-- pull이 다시 지우고, 저 기기는 또 올린다 — 두 기기가 영원히 싸운다. 사용자에게는
-- 「지웠는데 자꾸 돌아오는 녹음」으로 보인다.
--
-- 되돌리기: drop trigger block_purged_reinsert on journey.audio;

drop trigger if exists block_purged_reinsert on journey.audio;
create trigger block_purged_reinsert before insert on journey.audio
  for each row execute function journey.block_purged_reinsert();
