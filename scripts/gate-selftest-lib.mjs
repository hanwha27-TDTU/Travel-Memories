// gate-selftest-lib — 게이트 자체검사 실패를 **판정으로** 알리는 한 곳.
//
// 🔴 왜 공용 함수인가(2026-08-12 · M-0153). 헌법 §18-G는 *"전제가 없으면 판정하지 말고
//    말한다"*고 하고, 이 저장소의 종료코드 계약은 셋이다:
//
//      exit 0 = 통과      exit 1 = 재보고할 위반을 찾음      exit 2 = 전제 미충족(SKIP)
//
//    자체검사 실패는 **위반이 아니다.** 「이 게이트를 믿을 수 없다」이므로 `2`가 맞다.
//    그런데 게이트 23개가 `throw`로 죽고 있었다 — 던지면 스택과 함께 `exit 1`이 되고
//    하네스는 그것을 **「위반을 찾았다」**로 적는다. 판정문이 거짓이 되는 자리다.
//
// 🔴 왜 게이트마다 손으로 쓰지 않는가: 헌법 M-0060이 *"같은 판정을 두 번 쓰지 마라 —
//    이유를 붙여서도. 산문은 코드가 바뀔 때 같이 안 바뀐다"*고 적어 뒀다. 실제로 먼저 고친
//    형제들은 같은 `console.error(...); process.exit(2);`를 **열두 번 손으로** 반복했고,
//    그 열둘은 이미 조금씩 다른 문장을 쓰고 있었다. 여기 한 곳만 두면 갈라질 수 없다(§7 2층).
//
// 가정하는 세계(§18-G): 없음 — 순수 함수다. 파일·네트워크·기준가지를 읽지 않는다.

/**
 * 자체검사를 돌리고, 실패하면 **사유를 적고 `exit 2`로 나간다.**
 *
 * 던지든(`throw`) 실패 목록을 돌려주든(`string[]`) 둘 다 받는다 — 기존 게이트들이 두 형태로
 * 나뉘어 있고, 그 안에서 **무엇을 검사하는지는 건드리지 않는 것**이 이 전환의 핵심이기
 * 때문이다(§11 ②: 통과시키려고 판정 로직을 되돌리지 마라).
 *
 * @param {string} gateName 게이트 이름 — 판정문 맨 앞에 그대로 나간다.
 * @param {() => (void | string[])} fn 자체검사. 던지거나, 실패 사유 배열을 돌려준다.
 */
export function runSelfTest(gateName, fn) {
  let fails = [];
  try {
    fails = fn() ?? [];
  } catch (e) {
    fails = [e?.message ?? String(e)];
  }
  if (fails.length === 0) return;

  console.error(`${gateName}: **자체검사 실패** — 이 게이트를 믿을 수 없습니다(§4·§18-G).`);
  for (const f of fails) console.error(`  ✗ ${f}`);
  console.error('  → 이것은 **위반이 아닙니다.** 게이트 자신이 고장 났다는 뜻이므로,');
  console.error('     이번 실행은 이 층을 **재지 않은 것**입니다(SKIP≠PASS).');
  process.exit(2);
}
