import { createHash } from 'node:crypto';

export const EDGE_BEGIN = '// SYNC_RELEASE_CONTRACT:BEGIN';
export const EDGE_END = '// SYNC_RELEASE_CONTRACT:END';
const EDGE_OMITTED = '// SYNC_RELEASE_CONTRACT:OMITTED';

export function normalizeLf(text) {
  return String(text).replace(/\r\n?/g, '\n');
}

export function logicalEdgeSource(source) {
  const lf = normalizeLf(source);
  const generated = new RegExp(`${escapeRegExp(EDGE_BEGIN)}[\\s\\S]*?${escapeRegExp(EDGE_END)}`);
  if (generated.test(lf)) return lf.replace(generated, EDGE_OMITTED);
  const legacy = /export const FN_VERSION = \d+;\nexport const FN_OPS = \[[^\n]*\] as const;/;
  return lf.replace(legacy, EDGE_OMITTED);
}

export function sha256(text) {
  return createHash('sha256').update(normalizeLf(text), 'utf8').digest('hex');
}

export function edgeSourceSha256(source) {
  return sha256(logicalEdgeSource(source));
}

export function renderEdgeContractBlock(contract) {
  const ops = contract.mediaSign.requiredOps.map((op) => `'${op}'`).join(', ');
  return [
    EDGE_BEGIN,
    '// GENERATED by scripts/gen-sync-release-contract.mjs — edit schemas/sync-release-contract.json instead.',
    `export const FN_VERSION = ${contract.mediaSign.protocolVersion};`,
    `export const FN_OPS = [${ops}] as const;`,
    `export const FN_SOURCE_SHA256 = '${contract.mediaSign.sourceSha256}';`,
    EDGE_END,
  ].join('\n');
}

export function replaceEdgeContractBlock(source, block) {
  const lf = normalizeLf(source);
  const generated = new RegExp(`${escapeRegExp(EDGE_BEGIN)}[\\s\\S]*?${escapeRegExp(EDGE_END)}`);
  if (generated.test(lf)) return lf.replace(generated, block);
  const legacy = /export const FN_VERSION = \d+;\nexport const FN_OPS = \[[^\n]*\] as const;/;
  if (!legacy.test(lf)) throw new Error('media-sign의 FN_VERSION/FN_OPS 선언을 찾지 못했습니다.');
  return lf.replace(legacy, block);
}

export function renderClientContract(contract) {
  return `// GENERATED by scripts/gen-sync-release-contract.mjs — do not edit.\n` +
    `// SSOT: schemas/sync-release-contract.json\n` +
    `export const SYNC_RELEASE_CONTRACT = ${JSON.stringify(contract, null, 2)} as const;\n`;
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
