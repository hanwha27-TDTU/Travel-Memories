import type { TripStatus } from '../trip/homeSections';

/**
 * 타임라인을 **어느 쪽부터 보여줄 것인가**(사용자 지시 2026-08-15).
 *
 * ── 왜 「그냥 최신 먼저」가 아닌가 ──────────────────────────────────────────
 * 사용자가 물었다: *"정렬순서가 day 1부터인데 최신 순으로 하는데 어떨까?"*
 * 문제 제기는 정확했다 — **글을 쓰는 자리는 화면 맨 위**(순간 저장)인데 **그 결과는
 * 맨 아래**에 붙는다. 16일짜리 여행이면 오늘 기록을 보려고 매번 15일치를 스크롤한다.
 * §12가 말하는 *"앱이 사람에게 무엇을 대신 시키고 있는가"*의 전형이다.
 *
 * 🔴 **그런데 뒤집으면 다른 것을 잃는다.** 북극성은 *"여행 당시의 기억과 여행이 나에게
 * 남긴 의미를 다시 찾아주는"* 것이고, **여행은 앞에서 뒤로 읽히는 이야기**다. 나중에 다시
 * 볼 때 Day 16 → Day 1로 읽히면 이야기가 거꾸로 간다.
 *
 * **즉 두 상황이 정반대를 원한다** — 기록 중에는 최신이, 회고할 때는 Day 1이 위여야 한다.
 * 그래서 하나를 고르지 않고 **앱이 이미 아는 값**(여행 상태)으로 기본을 정한다.
 * §17 ②축: *"앱이 이미 아는 값을 판정에 안 쓰고 있으면 그게 모순의 씨앗이다."*
 *
 * 🔴 **사용자 선택이 언제나 이긴다.** 기본값은 추측이고 선택은 사실이다 — 추측이 사실을
 * 덮으면 그건 편의가 아니라 무시다.
 */
export type TimelineOrder = 'oldest' | 'newest';

/** 사용자가 이 여행에서 직접 고른 값. `null`이면 아직 안 골랐다는 뜻이다(「기본값과 같다」가 아니다). */
export type TimelineOrderChoice = TimelineOrder | null;

/**
 * 상태만 보고 정하는 기본값. **순수 함수** — 화면·저장소를 모른다(§10 ③).
 *
 * - `active`(진행 중) → **최신 먼저.** 지금 쓰는 중이므로 오늘이 손 닿는 곳에 있어야 한다.
 * - 그 밖(계획 중·완료·보관 중) → **Day 1 먼저.** 읽는 중이므로 이야기 순서를 지킨다.
 *
 * 🔴 `planned`가 왜 「Day 1 먼저」인가: 아직 기록이 거의 없어 스크롤 문제가 없고, 있다면
 * 그건 **계획**이라 앞에서 뒤로 읽는 것이 맞다. 「진행 중만 예외」가 이 함수의 전부다 —
 * 예외를 좁게 적는다(§19에서 배운 것: 넓게 적은 예외는 반드시 새어 나간다).
 */
export function defaultTimelineOrder(status: TripStatus): TimelineOrder {
  return status === 'active' ? 'newest' : 'oldest';
}

/** 실제로 쓸 순서. 고른 값이 있으면 그것이, 없으면 상태 기본값이 이긴다. */
export function timelineOrder(status: TripStatus, choice: TimelineOrderChoice): TimelineOrder {
  return choice ?? defaultTimelineOrder(status);
}

/**
 * 토글 버튼에 적을 말. 🔴 **지금 상태가 아니라 「누르면 무엇이 되는가」를 말한다.**
 *
 * 버튼 라벨이 *현재 상태*를 말하면 사용자는 그걸 「이걸 누르면 이렇게 된다」로 읽고 반대로
 * 누른다 — 이 저장소가 테마 토글에서 이미 쓰는 규율이다(`☀️ 라이트`는 *지금 다크*라는 뜻).
 * 둘을 한 함수에서 만들어 **문장과 동작이 어긋날 길을 없앤다**(§17 ②).
 */
export function orderToggleLabel(current: TimelineOrder): { label: string; ariaLabel: string; next: TimelineOrder } {
  // 🔴 **글리프는 앱이 실제로 그려내는 것만 쓴다.** 처음엔 `⇅`(U+21C5)를 썼는데 344px
  //    캡처에서 **네모/좁은 획으로 떨어졌다** — 화살표류 기호는 본문 폰트에 없으면 폴백한다.
  //    이 앱의 이모지(📷·👥·📍…)는 이모지 폰트로 확실히 그려지므로 그쪽 어휘를 쓴다.
  //    §13 1항이 말하는 「열어서 본다」가 아니었으면 못 잡았을 부류다(정적 검사는 못 본다).
  return current === 'newest'
    ? { label: '🕒 처음부터', ariaLabel: '첫날부터 보기로 바꾸기', next: 'oldest' }
    : { label: '🕒 최신부터', ariaLabel: '최근 날부터 보기로 바꾸기', next: 'newest' };
}
