// domain/place/photoProbe.ts — **앱이 받은 바이트의 사실을 사람이 읽을 문장으로.**
//
// ─────────────────────────────────────────────────────────────────────────────
// 왜 (2026-08-01 · M-0066 · 사용자)
// ─────────────────────────────────────────────────────────────────────────────
// *"계속 안되네..해시값을 계속 앱 내에서 바꾸는 듯?"*
//
// 나흘 동안 나는 **추측으로** 원인을 좁혔고 네 번 틀렸다(M-0054·56·58·59). 그때마다
// 사용자가 스크린샷을 찍어 날랐고 나는 그걸 보고 또 추측했다. §12가 금지하는 상태다:
// **앱이 아는 것을 말하지 않아 사람이 대신 나른다.**
//
// 그래서 이 문장은 **판정하지 않는다.** 관측만 적는다(§8) — 왜 그런지는 네 번 틀렸다.
// 사용자는 이 한 줄을 보내 주면 되고, 그 줄이 세 가설을 **한 번에** 가른다:
//
//   GPS 태그 없음        → 카메라가 위치를 안 적었다
//   GPS 태그 있음·값 0/0 → 누군가 비우고 넘겼다(선택기·전달 경로)
//   값이 정상            → **내 파서 결함**. 그 자리를 고친다
//
// 해시를 함께 적는 이유: 사용자가 폰의 원본과 **직접 대조**할 수 있다. 그러면
// *"앱 내에서 바꾸는 듯?"*이 추측이 아니라 **측정**이 된다.

import type { ExifProbe } from '../../media/exif';

export interface PhotoProbeFacts {
  name: string;
  bytes: number;
  /** SHA-256 앞 16자. 폰의 원본과 대조하기 위한 것 — 전부 적을 필요는 없다. */
  sha16: string;
  probe: ExifProbe;
}

/** `2,918,760` — 폰 파일 관리자가 보여주는 숫자와 눈으로 맞춰 보게. */
function comma(n: number): string {
  return n.toLocaleString('en-US');
}

/**
 * **관측 한 줄.** 판정어(「~때문입니다」)를 쓰지 않는다 — 이 함수는 원인을 모른다.
 *
 * 순수 함수인 이유(§10 ③): 사용자에게 나가는 문장은 유닛이 직접 돌려야 한다. 이 저장소는
 * 자료구조가 옳은데 **화면 문장만 틀린** 결함을 세 번 냈다(M-0022·M-0046·M-0061).
 */
export function photoProbeLine(f: PhotoProbeFacts): string {
  const head = `${f.name} · ${comma(f.bytes)}바이트 · sha256 ${f.sha16}…`;
  if (!f.probe.isJpeg) return `${head} · JPEG이 아니라 이 앱은 촬영정보를 못 읽어요(HEIC 등)`;

  const app1 = f.probe.app1.length ? f.probe.app1.join('→') : '없음';
  const when = f.probe.takenAtWall ? `촬영시각 ${f.probe.takenAtWall}` : '촬영시각 없음';
  const gps =
    f.probe.gps === 'value'
      ? `위치 있음 (${f.probe.gpsRaw ?? ''})`
      : f.probe.gps === 'zeroed'
        ? `위치 칸은 있는데 **값이 비어 있음** (${f.probe.gpsRaw ?? ''})`
        : '위치 칸 자체가 없음';
  return `${head} · 정보칸 ${app1} · ${when} · ${gps}`;
}

/**
 * **다음에 무엇을 하면 되는지** 한 줄. 관측에서 갈라지는 행동만 말한다.
 *
 * 🔴 원인을 말하지 않는다. *"선택기가 지웠어요"*는 M-0056에서 철회했고
 * *"파일에 원래 없었어요"*는 M-0059에서 무너졌다. **행동은 원인을 몰라도 고를 수 있다.**
 */
export function photoProbeNext(p: ExifProbe): string {
  if (!p.isJpeg) return '📍 [내 위치]로 넣어 주세요. 이 형식은 앱이 촬영정보를 못 읽어요.';
  if (p.gps === 'value') {
    return '🔴 값이 정상인데 안 들어갔다면 **앱 결함**입니다 — 이 줄을 그대로 보내 주세요.';
  }
  if (p.gps === 'zeroed') {
    // 🔴 문장을 뒤집었다(2026-08-01 10:27 실기기 · M-0068). 전에는 *"[📷 사진 추가](파일
    // 선택기)로 다시 골라 보시고, 그래도 같으면 이 줄을 보내 주세요"*였다 — 사용자가 정확히
    // 그렇게 했고 **같았다**(파일 선택기·갤러리 둘 다 0/0, 촬영시각은 읽힘). 이미 해 본 것을
    // 다시 시키는 안내는 안내가 아니다. 지금 되는 길만 말한다.
    return '위치 칸이 **비워진 채로** 앱에 왔어요 — 파일 선택기·갤러리 어느 쪽으로 골라도 이렇게 온 사례가 실측됐어요(폰이 브라우저에 넘기며 위치를 가리고 줄 수 있어요). 📍 [내 위치]나 🗺️ 지도·좌표 붙여넣기로 넣어 주세요 — 카메라로 바로 찍은 사진에는 위치가 들어와요.';
  }
  return '이 사진에는 위치 칸이 없어요. 카메라 「위치 태그」를 켜 두시면 앞으로 찍는 사진에 들어갑니다. 지금은 📍 [내 위치]가 가장 빠릅니다.';
}

// ─────────────────────────────────────────────────────────────────────────────
// 경로 줄 (2026-08-01 · M-0069)
// ─────────────────────────────────────────────────────────────────────────────
// 셸(v1.44)의 첫 실기기 보고가 「아직 0/0」이었는데, 관측 창은 GPS 사실만 말하고
// **바이트가 어느 문으로 들어왔는지**를 말하지 않아 스크린샷 한 장으로는 셸/PWA조차
// 못 갈랐다(둘 다 주소창이 없다). 실제로는 APK 미설치였고, 그걸 아는 데 왕복 하나를
// 썼다. 이 줄이 그 왕복을 없앤다 — 여기서도 **판정하지 않는다**, 경로 사실만 적는다(§8).

/** 관측 창이 넘겨주는 경로 사실 — services/nativePhotos가 기록한 것을 그대로 받는다. */
export interface PhotoPathFacts {
  /** 실행 환경: 브라우저(PWA 포함) / 셸 / 셸인데 네이티브 문 없음(옛 APK). */
  shell: 'browser' | 'shell' | 'shell-no-plugin';
  /** 이 파일이 네이티브 문을 거쳤다면 그때의 사실, 아니면 null. */
  picked: { original: boolean; reason: string } | null;
}

/**
 * **바이트가 어느 문으로 들어왔는지** 한 줄. 순수 함수(§10 ③) — 이 문장도 사용자에게 간다.
 *
 * 🔴 원인 단정어를 쓰지 않는다(§8 — 유닛이 잠근다). `reason`은 플러그인이 적은 사실
 * 문자열이라 **가공 없이 그대로** 내보낸다(가공하면 대조할 수 없다 — 해시와 같은 규율).
 */
export function photoProbePath(f: PhotoPathFacts): string {
  if (f.shell === 'browser') {
    return '경로: 브라우저 — 원본 승격 문 없이 들어왔어요. 갤러리 사진의 위치를 살리는 문은 셸(APK) 안에만 있어요.';
  }
  if (f.shell === 'shell-no-plugin') {
    return '경로: 셸인데 네이티브 문이 없어요 — APK가 옛 판일 수 있어요(새 APK 설치가 필요해요). 이 줄을 그대로 보내 주세요.';
  }
  if (!f.picked) {
    return '경로: 셸인데 이 파일은 네이티브 문을 거치지 않고 들어왔어요(시스템 선택기 경로). 이 줄을 그대로 보내 주세요.';
  }
  return f.picked.original
    ? '경로: 셸 · 네이티브 문 · 원본 승격 ✓'
    : `경로: 셸 · 네이티브 문 · 원본 승격 안 됨 (사유: ${f.picked.reason}) — 이 줄을 그대로 보내 주세요.`;
}
