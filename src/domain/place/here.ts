// domain/place/here.ts — **지금 내가 있는 자리**를 장소로 쓸 때의 판정(순수).
//
// ─────────────────────────────────────────────────────────────────────────────
// 왜 (사용자 2026-07-31)
// ─────────────────────────────────────────────────────────────────────────────
// *"내가 원하는 건 장소가 바로 입력되게 하고 싶은거야. 어떤 방식이든 결과가 중요함."*
//
// 맞는 요구다. 그리고 우리는 **엉뚱한 문을 두드리고 있었다** — 사진 EXIF의 GPS는
// 안드로이드 13+의 사진 선택기가 앱에 넘기기 전에 지운다(M-0054에서 실기기로 확정).
// 파서를 고쳐도 못 읽는다. 바이트에 이미 없기 때문이다.
//
// 그런데 **기기는 자기가 지금 어디 있는지 알고 있다.** `navigator.geolocation`은
// 사진과 무관하게 동작하고, 안드로이드가 막는 대상도 아니며(사용자가 허용하면 그만),
// 오프라인에서도 GPS로 답한다. 여행 중 그 자리에서 기록하는 흐름 — 이 앱의 주 흐름 —
// 에서는 **사진 EXIF보다 오히려 정확한 근거**다.
//
// ─────────────────────────────────────────────────────────────────────────────
// 🔴 그러나 「지금 여기」는 **「그때 거기」가 아니다**
// ─────────────────────────────────────────────────────────────────────────────
// 이 모듈이 존재하는 진짜 이유가 이것이다. 소급 입력(집에 와서 어제 여행을 정리)에서
// 현재 위치를 자동으로 넣으면 **기억이 집 주소에 찍힌다.** 그리고 그 오류는 조용하다 —
// 사용자는 자기가 넣지 않은 좌표가 들어간 줄도 모른다(원칙 #1·§8).
//
// 그래서 이 판의 결정은 **「자동으로 넣지 않는다. 대신 한 번 눌러 끝나게 한다」**이다.
//
// 사용자가 실제로 겪은 값이 그 근거다 — **20:19에 14:09**에 찍은 사진을 넣고 있었다(6시간 차).
// 그때 현재 위치를 조용히 넣었다면 **의정부 버스터미널의 기억이 집 주소에 찍혔을 것**이고,
// 사용자는 자기가 넣지 않은 좌표가 들어간 줄도 몰랐을 것이다(원칙 #1·§8).
//
// 버튼을 누르는 것은 *"지금 여기가 맞다"*는 **사용자의 판단**이다. 그건 앱이 대신할 수 없고,
// 대신하면 조용히 틀린다. 대신 앱이 할 일은 **누르기 쉽게 만드는 것** — 그래서 버튼은
// 장소 칸에 상시로 있고, 사진에 위치가 없을 때의 안내가 그 버튼을 가리킨다.

import { precisionFromSpan, type PrecisionVerdict } from './precision';

/** 위치를 못 얻은 이유. 각각 **사용자가 할 일이 다르므로** 뭉개지 않는다(§8). */
export type HereFail = 'denied' | 'unavailable' | 'timeout' | 'unsupported';

/**
 * GPS 정확도(m) → **이미 있는 정밀도 체계**로 판정.
 *
 * 왜 새로 만들지 않는가: 화면은 이미 「📍 건물·지점 · 약 50m」/「⚠ 길 전체를 가리켜요」를
 * 말할 줄 안다. 위치 출처가 검색이든 지도든 GPS든 **사용자가 알아야 하는 것은 같다** —
 * *이 좌표가 얼마나 좁은 곳을 가리키는가*. 여기서 등급을 새로 정의하면 같은 사실을
 * 두 어휘로 말하게 된다(§7 사용자 대면 대칭).
 *
 * 정확도는 **반지름**이고 우리 체계의 `span`은 **지름**이라 2배로 넘긴다. 실내 wifi 측위가
 * 2km로 오는 일이 실제로 있고, 그걸 「📍 위치 지정됨」이라고만 적으면 그게 M-0024의 형태다.
 */
export function hereVerdict(accuracyM: number | null): PrecisionVerdict {
  const span = accuracyM !== null && Number.isFinite(accuracyM) && accuracyM >= 0 ? Math.round(accuracyM * 2) : null;
  const precision = precisionFromSpan(span);
  return { precision, spanMeters: span, pinpoint: precision === 'point' };
}

/**
 * 배지에 적을 근거 — **숫자 좌표를 함께 보여준다**(사용자 2026-07-31:
 * *"사진 업로드와 동시에 내게 좌표를 제공해주면 내가 직접 입력하면 되지 않아?"*).
 *
 * 왜 숫자를 노출하나: 사용자의 목적이 *"무료 지도 자체가 위치가 정확하지 않아서 GPS 도움을
 * 받으려는 것"*이다. 그러면 앱이 「위치 지정됨」이라고만 말하는 것은 **아무 도움이 안 된다** —
 * 확인할 수도, 다른 곳에 옮겨 적을 수도, 다른 지도앱에서 대조할 수도 없다.
 * 좌표는 **사용자가 가져갈 수 있는 형태**로 화면에 있어야 한다(§12).
 *
 * 소수점 5자리 = 약 1m. 그보다 더 적으면 GPS 정밀도를 버리는 것이고, 더 많으면 읽히지 않는다.
 * 정확도를 모르면 **모른다고 두고** 지어내지 않는다(§8).
 */
export function hereLabel(coord: { lat: number; lng: number }, accuracyM: number | null): string {
  const at = `${coord.lat.toFixed(5)}, ${coord.lng.toFixed(5)}`;
  if (accuracyM === null || !Number.isFinite(accuracyM) || accuracyM < 0) return `지금 내 위치 · ${at}`;
  const m = Math.round(accuracyM);
  const acc = m < 1000 ? `±${m}m` : `±${(m / 1000).toFixed(1)}km`;
  return `지금 내 위치 · ${at} (${acc})`;
}

/**
 * 실패 사유 → **다음에 할 일이 담긴** 한 문장(§12 — 「안 됩니다」로 끝내지 않는다).
 *
 * 넷을 나눠 두는 이유: 권한을 껐을 때와 실내라 못 잡을 때는 **사용자가 할 일이 정반대**다.
 * 하나로 뭉개면 권한을 켜야 할 사람이 계속 버튼만 누르고, 잠시 기다리면 될 사람이
 * 설정을 뒤진다.
 */
export function hereFailMessage(fail: HereFail): string {
  switch (fail) {
    case 'denied':
      return '📍 위치 권한이 꺼져 있어요 — 주소창의 자물쇠(또는 브라우저 설정)에서 위치를 허용해 주세요. 🗺️ 지도로 직접 찍으셔도 됩니다';
    case 'unavailable':
      return '📍 지금 위치를 잡지 못했어요(실내·지하일 수 있어요) — 잠시 뒤 다시 누르거나 🗺️ 지도로 찍어 주세요';
    case 'timeout':
      return '📍 위치를 찾는 데 너무 오래 걸렸어요 — 다시 누르거나 🗺️ 지도로 찍어 주세요';
    case 'unsupported':
      return '📍 이 브라우저는 위치를 알려주지 않아요 — 🗺️ 지도로 찍거나 좌표를 붙여넣어 주세요';
  }
}
