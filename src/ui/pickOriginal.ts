// ui/pickOriginal.ts — **원본 파일로 고르는 길** 하나.
//
// ─────────────────────────────────────────────────────────────────────────────
// 왜 (사용자 실기기 스크린샷 2026-07-31 · 갤러리 상세 화면)
// ─────────────────────────────────────────────────────────────────────────────
// 갤러리가 그 사진의 위치를 **지도로 보여주고 있었다** — 「대한민국 충청북도 청주시 상당구」,
// `/내장 저장공간/DCIM/Camera/20260731_194400.jpg`.
//
// 즉 **파일 안에 GPS가 분명히 있다.** 앱이 못 읽는 것이 아니라, 안드로이드 13+의
// **사진 선택기가 앱에 넘기면서 지우는 것**이다(M-0054). 파서를 고쳐도 소용없던 이유이고,
// 동시에 **뚫을 길이 있다는 뜻**이기도 하다 — 사진 선택기를 안 거치면 된다.
//
// ─────────────────────────────────────────────────────────────────────────────
// 어떻게
// ─────────────────────────────────────────────────────────────────────────────
// 크롬은 `accept`가 **사진·영상 MIME만**일 때 안드로이드 사진 선택기를 쓴다. 목록에
// 사진이 아닌 형식이 하나라도 섞이면 그 선택기로는 처리할 수 없어 **일반 파일 선택기**로
// 내려간다. 파일 선택기는 원본 바이트를 그대로 넘기므로 EXIF가 살아 있다.
//
// 🔴 **2026-08-01: 사용자가 실기기에서 쟀고, 기본값을 뒤집었다.**
//
// 처음엔 *"내가 재본 것이 아니다"*(§13 3항)를 이유로 **별도 버튼 뒤에** 숨겨 뒀다. 그 신중함이
// 여기서는 **비쌌다** — 기본 경로가 계속 위치를 잃는 동안, 나는 「앱이 받은 바이트 = 원본
// 바이트」를 전제로 파서·순서·게이트를 뒤지고 있었다. 사용자가 정확히 그 지점을 지적했다:
// *"계속 니 코딩이 맞다고 가정하고 원인을 찾지마. 바뀌지 않는 건 앱에 올라갈 때 해시가
// 바뀌고 있다는 거야."*
//
// 실기기 측정(사용자):
//   · 📁 원본에서 / 직접 촬영  → 좌표 **살아 있음**(00:19 — 36.60916, 127.50248 + 주소)
//   · 📷 사진 추가(기본 선택기) → 좌표 **없음**(01:44, 그리고 그 전 전부)
//
// **재보지 않았다는 이유로 기본값을 안 바꾼 것**과 **재본 뒤에도 안 바꾸는 것**은 다르다.
// 이제 원본 경로가 기본이고, 갤러리 선택기는 **명시적으로 고를 때만** 쓴다 — 사용자 요구가
// *"어떤 방식이든 결과가 중요함"*이기 때문이다.

/**
 * 사진 선택기가 처리할 수 없는 형식을 하나 섞어 **일반 파일 선택기**로 내려보낸다.
 * **이것이 사진 입력칸의 기본값이다**(2026-08-01) — 원본 바이트가 그대로 와야 위치가 산다.
 */
export const ORIGINAL_ACCEPT = 'image/*,application/octet-stream';

/**
 * 갤러리(사진 선택기)를 여는 `accept`. **위치가 지워질 수 있다** — 사용자가 편의를 위해
 * 명시적으로 고를 때만 쓴다. 기본값으로 되돌리지 마라(그 순간 위치가 조용히 사라진다).
 */
export const GALLERY_ACCEPT = 'image/*';

/**
 * 입력칸의 `accept`를 **한 번만** 바꿔서 열고, 끝나면 되돌린다.
 *
 * 입력칸을 **새로 만들지 않는다** — 하나를 두 방식으로 여는 것뿐이라, 고른 뒤의 처리
 * (미리보기·EXIF·압축·저장)는 **기존 경로를 그대로 지난다.** 두 번째 입력칸을 만들면
 * 그 처리를 한 벌 더 손으로 배선하게 되고, 그 순간 한쪽이 낡는다(§7 2층).
 *
 * `accept`는 **원래대로 되돌린다.** 안 되돌리면 다음에 평소처럼 [사진 추가]를 눌러도
 * 파일 선택기가 열려, 사용자가 고치지 않은 동작이 조용히 바뀐다(§3-C의 화면판).
 * 고른 경우(`change`)와 취소한 경우(`focus` 복귀) 둘 다 되돌린다 — 취소를 안 다루면
 * **취소했을 때만** 설정이 남는다.
 */
/**
 * 이 열기가 **셸의 네이티브 가로채기를 비켜서는가**(`nativePhotos.wireNativeIntake`).
 *
 * 🔴 **기본값을 두지 않는다**(M-0060 — 갈라질 수 있는 판정은 이유를 붙여 인자로 넘긴다).
 *    새 호출부는 이 값을 적을 수밖에 없고, 그때 *"셸에서 이 버튼은 무슨 문을 열어야 하나"*를
 *    반드시 한 번 판단하게 된다. 이 표시가 없어서 「갤러리에서」가 갤러리를 못 열었다.
 */
export interface AltPickIntent {
  /** true면 셸 안에서도 시스템 선택기가 열린다 — 사용자가 그 대가(위치 누락)를 알고 고른 길일 때만. */
  bypassNativeIntake: boolean;
}

/** 셸 가로채기가 읽는 표시. 켜져 있는 동안의 click 한 번만 비켜선다. */
export const BYPASS_NATIVE_ATTR = 'bjBypassNative';

export function wireAltPick(
  input: HTMLInputElement,
  btn: HTMLButtonElement,
  accept: string,
  intent: AltPickIntent,
): void {
  btn.addEventListener('click', () => {
    const keep = input.accept;
    let restored = false;
    const restore = (): void => {
      if (restored) return;
      restored = true;
      input.accept = keep;
      // 🔴 표시도 **함께** 되돌린다. 남으면 다음에 평소처럼 [📷 사진 추가]를 눌러도 셸이
      //    비켜서서 위치가 조용히 사라진다 — `accept`를 되돌리는 것과 같은 이유다.
      delete input.dataset[BYPASS_NATIVE_ATTR];
    };
    input.accept = accept;
    if (intent.bypassNativeIntake) input.dataset[BYPASS_NATIVE_ATTR] = '1';
    input.addEventListener('change', restore, { once: true });
    // 취소하면 `change`가 오지 않는다. 파일 대화상자가 닫히며 창이 초점을 되찾는 것을 쓴다.
    window.addEventListener('focus', restore, { once: true });
    input.click();
  });
}
