// 사용자 결정(2026-07-27): *"처음 한 번만 확인."* 개인정보 원칙은 지키되(무엇이 나가는지
// 말한다) 누를 때마다 묻지는 않는다 — 매번 묻는 확인은 읽히지 않고 반사적으로 눌리기 때문에,
// 세 번째부터는 **고지가 아니라 마찰**이다.
//
// 그 판단이 처음엔 바깥 지도 하나뿐이라 `externalMapConsent.ts`에 인라인으로 있었다. 그런데
// **사진 위치를 지오코더에 보내는 두 번째 자리**가 생겼다(사용자 제안 2026-07-30 — 「사진에서
// 장소를 가져오자」). 같은 규율을 두 곳에 손으로 구현하는 순간 드리프트는 시간 문제이고,
// 여기 담긴 것이 **개인정보 동의**라 한쪽만 낡으면 조용히 새어 나간다(§7 2층).
//
// 🔴 **못 읽으면 「동의 안 함」이다.** 프라이빗 모드 등으로 localStorage가 막히면 모르는
// 것이지 동의한 것이 아니다 — 모르는 것을 동의로 반올림하지 않는다(비타협 원칙 #4).
//
// 동의 여부는 기억(memory)이 아니라 **이 기기의 표시 상태**라 localStorage에 둔다
// (`backupMeta.ts`와 같은 판단 — 사이트데이터가 지워지면 다시 한 번 묻게 될 뿐 무해하다).
// 그래서 백업·동기화 대상이 아니다: `purgedIds`를 백업에서 제외한 것과 같은 근거다.

/** 이 기기에서 이 항목에 대해 이미 확인했는가. */
export function hasAgreed(key: string): boolean {
  try {
    return localStorage.getItem(key) === '1';
  } catch {
    return false;
  }
}

export function rememberAgreed(key: string): void {
  try {
    localStorage.setItem(key, '1');
  } catch {
    /* 못 적으면 다음에 한 번 더 묻게 될 뿐 — 기능 자체를 막지 않는다. */
  }
}

